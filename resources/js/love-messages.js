let lastIndexes = [];

export function getRandomMessage() {
  const total = LOVE_MESSAGES.length;
  const avoidCount = Math.min(40, Math.floor(total * 0.3));
  let idx;
  do {
    idx = Math.floor(Math.random() * total);
  } while (lastIndexes.includes(idx));
  lastIndexes.push(idx);
  if (lastIndexes.length > avoidCount) lastIndexes.shift();
  return LOVE_MESSAGES[idx];
}

